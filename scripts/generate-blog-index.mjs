import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const blogDirectory = fileURLToPath(new URL("../src/data/blog/", import.meta.url));
const outputFile = fileURLToPath(new URL("../src/data/blog/index.ts", import.meta.url));
const folders = readdirSync(blogDirectory, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(`${blogDirectory}/${entry.name}/blog.mdx`))
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

const imports = folders.map((folder, index) =>
  `import Blog${index}, { frontmatter as frontmatter${index} } from ${JSON.stringify(`./${folder}/blog.mdx`)};`,
).join("\n");

const entries = folders.map((_, index) => `  entry(frontmatter${index}, Blog${index}),`).join("\n");
const generated = `// Generated by scripts/generate-blog-index.mjs. Do not edit manually.
${imports}
import type { BlogEntry, BlogFrontmatter } from "../../typeDefs/blog";

const entry = (frontmatter: BlogFrontmatter, Content: BlogEntry["Content"]): BlogEntry => ({
  frontmatter,
  Content,
});

export const blogEntries = [
${entries}
].sort((a, b) => Date.parse(b.frontmatter.date) - Date.parse(a.frontmatter.date));

export const blogSummaries = blogEntries.map(({ frontmatter }) => frontmatter);

export function getBlog(slug: string) {
  return blogEntries.find(({ frontmatter }) => frontmatter.slug === slug);
}
`;

if (!existsSync(outputFile) || readFileSync(outputFile, "utf8") !== generated) {
  writeFileSync(outputFile, generated);
}
